def topic_id(domain: int, number: int) -> str:
    return f"D{domain:02d}-T{number:02d}"


def iter_topics():
    for domain, (_title, _folder, names) in DOMAINS.items():
        for index, name in enumerate(names, start=1):
            yield domain, index, topic_id(domain, index), name


def chapter_for(domain: int, number: int) -> tuple[str, str, str]:
    folder = DOMAINS[domain][1]
    for filename, title, _difficulty, numbers in CHAPTERS[domain]:
        if number in numbers:
            return f"{folder}/{filename}", title, _difficulty
    raise KeyError(f"No chapter for {topic_id(domain, number)}")


def assert_coverage() -> None:
    for domain, (_title, _folder, names) in DOMAINS.items():
        assigned: list[int] = []
        for _filename, _title2, _difficulty, numbers in CHAPTERS[domain]:
            assigned.extend(numbers)
        expected = list(range(1, len(names) + 1))
        if sorted(assigned) != expected:
            missing = set(expected) - set(assigned)
            extra = set(assigned) - set(expected)
            dupes = [n for n in assigned if assigned.count(n) > 1]
            raise SystemExit(
                f"Domain {domain} chapter map mismatch missing={sorted(missing)} extra={sorted(extra)} dupes={sorted(set(dupes))}"
            )


assert_coverage()
